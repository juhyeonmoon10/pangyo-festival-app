const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {pathToFileURL} = require('node:url');
const {chromium} = require(process.env.PLAYWRIGHT_PATH || 'playwright');
const site = path.resolve(__dirname,'..');
const output = path.join(site,'artifacts/ui-ver2');

(async () => {
  fs.mkdirSync(output,{recursive:true});
  const browser = await chromium.launch({headless:true, executablePath:process.env.CHROME_PATH});
  const reports = [];
  try {
    for (const width of [320,390,430,1024]) {
      const page = await browser.newPage({viewport:{width,height:844},hasTouch:true,isMobile:width<500});
      const errors = [];
      page.on('pageerror',error => errors.push(error.message));
      await page.route('https://**/*',route => route.fulfill({json:[]}));
      const capture = async label => {
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth),true,`horizontal overflow: ${width}/${label}`);
        const missingImages = await page.locator('img').evaluateAll(images => images.filter(image => image.complete && !image.naturalWidth).map(image => image.src));
        assert.deepEqual(missingImages,[],`missing images: ${label}`);
        await page.screenshot({path:path.join(output,`${width}-${label}.png`),fullPage:true,animations:'disabled'});
      };
      await page.goto(pathToFileURL(path.join(site,'index.html')).href + '?demo=1');
      await capture('login');
      await page.locator('#googleLogin').click();
      await page.waitForSelector('.home-v2');
      await capture('home');
      assert.equal(await page.locator('.home-map #mapCard').count(),1);
      await page.locator('[data-floor="2"]').click();
      await capture('home-second-floor');
      await page.locator('#mapSearchBtn').click();
      const input = page.locator('#searchScreenInput');
      await input.fill('1학년 1반');
      const spaced = await page.locator('#searchResultList [data-list-select]').evaluateAll(nodes => nodes.map(node=>node.dataset.listSelect));
      await input.fill('1학년1반');
      assert.deepEqual(await page.locator('#searchResultList [data-list-select]').evaluateAll(nodes=>nodes.map(node=>node.dataset.listSelect)),spaced);
      assert.equal(spaced.includes('g1-1'),true);
      await page.evaluate(async () => {
        const input = document.querySelector('#searchScreenInput');
        window.savedSearchInput = input;
        input.dispatchEvent(new CompositionEvent('compositionstart',{bubbles:true}));
        input.value = '1학년';
        input.dispatchEvent(new InputEvent('input',{bubbles:true,isComposing:true}));
        const token = mockNfcTokenForTagId(state.db.booths.find(booth=>booth.id==='g1-1').nfcTagId);
        await nfcAdapter.scan(createNfcClaim(token,'android-nfc'));
        if (input !== document.querySelector('#searchScreenInput')) throw Error('NFC replaced composing input');
        if (document.activeElement !== input) throw Error('NFC stole keyboard focus');
        input.value = '1학년1반';
        input.dispatchEvent(new CompositionEvent('compositionend',{bubbles:true}));
      });
      assert.equal(await page.evaluate(()=>state.route),'home');
      assert.equal(await page.evaluate(()=>repo.stampsForUser(state.user.id).length),1);
      assert.equal(await page.locator('#searchResultList [data-booth-visited="g1-1"]').innerText(),'방문 완료');
      await capture('search-nfc');
      await page.locator('.feedback-close').click();
      await page.locator('#closeSearchScreen').click();
      await page.waitForSelector('#searchScreenInput',{state:'detached'});
      await page.locator('.bottom-nav [data-route="map"]').click();
      const grip = await page.locator('#sheetToggle').boundingBox();
      const nav = await page.locator('.bottom-nav').boundingBox();
      const sheet = await page.locator('#sheet').boundingBox();
      assert.ok(Math.abs(sheet.y+sheet.height-nav.y)<2,'sheet must touch navigation');
      await page.mouse.move(grip.x+grip.width/2,grip.y+grip.height/2);
      await page.mouse.down();
      await page.mouse.move(grip.x+grip.width/2,170,{steps:12});
      await page.mouse.up();
      assert.equal(await page.evaluate(()=>state.sheetLevel),'full');
      await capture('map-sheet');
      await page.waitForTimeout(450);
      await page.locator('#sheetToggle').click();
      assert.equal(await page.evaluate(()=>state.sheetLevel),'peek');
      await page.locator('#mapZoomIn').click();
      assert.ok(await page.evaluate(()=>state.mapZoom>1));
      await capture('map');
      await page.locator('[data-map-select="g1-1"]').click();
      await capture('preview');
      await page.locator('.preview-detail-btn').click();
      await page.locator('#submitReview').click();
      assert.match(await page.locator('#reviewFeedback').innerText(),/별점/);
      await page.locator('[data-rating="4"]').click();
      await page.locator('#submitReview').dblclick();
      assert.equal(await page.evaluate(()=>state.db.reviews.filter(review=>review.userId===state.user.id&&review.boothId==='g1-1').length),1);
      assert.equal(await page.evaluate(()=>state.db.reviews.find(review=>review.userId===state.user.id&&review.boothId==='g1-1').content),'');
      await capture('detail-rated');
      await page.evaluate(async()=>{
        const token = mockNfcTokenForTagId(state.db.booths.find(booth=>booth.id==='g1-2').nfcTagId);
        await Promise.all([nfcAdapter.scan(createNfcClaim(token,'android-nfc')),nfcAdapter.scan(createNfcClaim(token,'android-nfc'))]);
      });
      assert.equal(await page.evaluate(()=>state.route),'detail');
      assert.equal(await page.evaluate(()=>repo.stampsForUser(state.user.id).length),2);
      await page.evaluate(() => dismissNfcFeedback());
      await page.locator('.bottom-nav [data-route="stamps"]').click();
      assert.equal(await page.locator('.pass-row.earned').count(),2);
      assert.equal(await page.locator('.trail-stop.earned').count(),2);
      await capture('pass');
      await page.locator('#toggleStampTrail').click();
      assert.equal(await page.locator('.trail-stop').count(),await page.evaluate(()=>state.db.booths.length));
      await page.locator('.bottom-nav [data-route="home"]').click();
      await page.locator('[data-open-reviews]').click();
      assert.equal(await page.locator('.review-picker [data-review-booth]').count(),1);
      await capture('review-picker');
      await page.keyboard.press('Escape');
      await page.waitForSelector('.review-picker',{state:'detached'});
      await page.locator('.bottom-nav [data-route="scan"]').click();
      assert.equal(await page.locator('.nfc-test-panel').count(),0,'student must not see mock tools');
      await capture('nfc');
      await page.locator('.bottom-nav [data-route="profile"]').click();
      await capture('profile');
      assert.deepEqual(errors,[]);
      reports.push({width,pass:true,screens:12,imePreserved:true,nfcDoesNotNavigate:true,ratingWithoutText:true,duplicatePrevented:true,sheetAttached:true});
      await page.close();
    }
    fs.writeFileSync(path.join(output,'report.json'),JSON.stringify(reports,null,2));
    console.log(JSON.stringify(reports,null,2));
  } finally { await browser.close(); }
})().catch(error=>{console.error(error);process.exitCode=1;});

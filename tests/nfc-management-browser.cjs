const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'playwright');
const site = path.resolve(__dirname, '..');
const output = path.join(site, 'artifacts/nfc-management');

(async () => {
  fs.mkdirSync(output, { recursive: true });
  const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_PATH });
  const reports = [];
  try {
    for (const width of [320, 390, 430, 1024]) {
      const page = await browser.newPage({ viewport: { width, height: 844 } });
      const errors = [];
      page.on('pageerror', error => errors.push(error.message));
      await page.route('https://**/*', route => route.fulfill({ json: [] }));
      const capture = async name => {
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `${width}: overflow`);
        assert.equal((await page.locator('#nfcManager').innerText()).includes('<span'), false, 'template markup must not appear as booth names');
        await page.screenshot({ path: path.join(output, `${width}-${name}.png`), fullPage: true, animations: 'disabled' });
      };
      await page.goto(pathToFileURL(path.join(site, 'index.html')).href + '?demo=1');
      await page.locator('#adminLogin').click();
      await page.locator('[data-toggle-menu="admin-tab"]').click();
      await page.locator('[data-admin-tab="booths"]').click();
      await page.waitForSelector('#nfcManager');
      assert.equal(await page.locator('#nfcSettingsForm').count(), 1);
      assert.equal(await page.locator('.nfc-booth-row').count(), 29);
      await capture('overview');
      const search = page.locator('#nfcManagerSearch');
      await search.fill('1학년 1반');
      const spaced = await page.locator('[data-nfc-select]').evaluateAll(nodes => nodes.map(node => node.dataset.nfcSelect));
      await search.fill('1학년1반');
      assert.deepEqual(await page.locator('[data-nfc-select]').evaluateAll(nodes => nodes.map(node => node.dataset.nfcSelect)), spaced);
      assert.deepEqual(spaced, ['g1-1']);
      await page.evaluate(() => {
        const input = document.querySelector('#nfcManagerSearch');
        window.originalManagerSearch = input;
        input.dispatchEvent(new CompositionEvent('compositionstart', { bubbles: true }));
        input.value = '인벨';
        input.dispatchEvent(new InputEvent('input', { bubbles: true, isComposing: true }));
        input.value = '인벨릭스';
        input.dispatchEvent(new CompositionEvent('compositionend', { bubbles: true }));
        if (input !== document.querySelector('#nfcManagerSearch') || document.activeElement !== input) throw Error('Manager lost IME input');
      });
      assert.equal(await page.locator('[data-nfc-select]').count(), 1);
      await search.fill('1학년1반');
      await page.locator('[data-nfc-select="g1-1"]').click();
      await page.locator('#nfcManagerTag').fill('NFC-MANAGER-TEST');
      await page.locator('#nfcManagerStatus').selectOption('paused');
      await page.locator('#nfcManagerSearch').fill('1학년2반');
      await page.locator('[data-nfc-select="g1-2"]').click();
      await page.locator('#nfcManagerSearch').fill('1학년1반');
      await page.locator('[data-nfc-select="g1-1"]').click();
      assert.equal(await page.locator('#nfcManagerTag').inputValue(), 'NFC-MANAGER-TEST');
      assert.equal(await page.locator('#nfcManagerStatus').inputValue(), 'paused');
      await page.locator('[data-nfc-action="check"]').click();
      assert.match(await page.locator('#nfcManagerResult').innerText(), /먼저 저장/);
      const originalTag = await page.evaluate(() => state.db.booths.find(b => b.id === 'g1-1').nfcTagId);
      const duplicateTag = await page.evaluate(() => state.db.booths.find(b => b.id === 'g1-2').nfcTagId);
      await page.locator('#nfcManagerTag').fill(duplicateTag.toLowerCase());
      await page.locator('#nfcManagerSave').click();
      assert.match(await page.locator('#nfcManagerResult').innerText(), /이미 등록/);
      assert.equal(await page.evaluate(() => state.db.booths.find(b => b.id === 'g1-1').nfcTagId), originalTag);
      await page.locator('#nfcManagerTag').fill('nf1.not-a-real-token');
      await page.locator('#nfcManagerSave').click();
      assert.match(await page.locator('#nfcManagerResult').innerText(), /NFC-/);
      await page.locator('#nfcManagerTag').fill('NFC-MANAGER-TEST');
      await page.evaluate(() => { window.savedWriteStorage = writeStorage; writeStorage = () => false; });
      await page.locator('#nfcManagerSave').click();
      assert.match(await page.locator('#nfcManagerResult').innerText(), /저장 공간/);
      assert.equal(await page.evaluate(() => state.db.booths.find(b => b.id === 'g1-1').nfcTagId), originalTag);
      await page.evaluate(() => { writeStorage = window.savedWriteStorage; });
      await page.locator('#nfcManagerSave').click();
      assert.equal(await page.evaluate(() => state.db.booths.find(b => b.id === 'g1-1').nfcTagId), 'NFC-MANAGER-TEST');
      assert.equal(await page.locator('#nfcManagerStatus').inputValue(), 'paused');
      await page.locator('[data-nfc-action="check"]').click();
      assert.match(await page.locator('#nfcManagerResult').innerText(), /확인이 필요한 설정/);
      await page.locator('#nfcManagerStatus').selectOption('open');
      await page.locator('#nfcManagerSave').click();
      await page.locator('[data-nfc-action="check"]').click();
      assert.match(await page.locator('#nfcManagerResult').innerText(), /설정 점검 통과/);
      assert.equal(await page.evaluate(() => state.db.stamps.length), 0);
      await page.locator('[data-nfc-action="simulate"]').dblclick();
      await page.waitForFunction(() => state.db.stamps.length === 1);
      assert.equal(await page.evaluate(() => state.route), 'admin');
      assert.equal(await page.evaluate(() => state.db.stamps.every(s => s.userId === state.user.id)), true);
      await page.locator('.feedback-close').click();
      await page.locator('[data-nfc-action="simulate"]').click();
      await page.waitForFunction(() => document.querySelector('#nfcManagerResult')?.textContent.includes('중복 방지 확인'));
      assert.equal(await page.evaluate(() => state.db.stamps.length), 1);
      await page.locator('.feedback-close').click();
      await capture('test-result');
      await page.locator('#nfcManagerEnabled').uncheck();
      await page.locator('#nfcManagerSave').click();
      const disabled = await page.evaluate(async () => {
        const result = await nfcAdapter.scan(createNfcClaim(mockNfcTokenForTagId('NFC-MANAGER-TEST'), 'mock-panel'));
        return { code: result.code, count: state.db.stamps.length };
      });
      assert.deepEqual(disabled, { code: 'NFC_TAG_DISABLED', count: 1 });
      await page.locator('.feedback-close').click();
      await page.locator('#nfcManagerSearch').fill('');
      await page.locator('#nfcManagerFilter').selectOption('disabled');
      assert.equal(await page.locator('[data-nfc-select]').count(), 1);
      await capture('disabled');
      await page.locator('#nfcManagerTag').fill('NFC-NEW-DRAFT');
      await page.locator('[data-nfc-action="discard"]').click();
      assert.equal(await page.locator('#nfcManagerTag').inputValue(), 'NFC-MANAGER-TEST');
      await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async text => { window.copiedNfcUrl = text; } } }));
      await page.locator('[data-nfc-action="copy"]').click();
      assert.equal(await page.evaluate(() => window.copiedNfcUrl), 'pangyofestival://nfc?nfc=NFC-MANAGER-TEST');
      await page.reload();
      await page.locator('#adminLogin').click();
      const persisted = await page.evaluate(() => state.db.booths.find(b => b.id === 'g1-1'));
      assert.equal(persisted.nfcEnabled, false);
      assert.equal(persisted.nfcTagId, 'NFC-MANAGER-TEST');
      const guard = await page.evaluate(() => {
        const before = JSON.stringify(state.db);
        state.user = { id: 'student-test', role: 'user' };
        state.route = 'admin';
        render();
        return { hasEditor: Boolean(document.querySelector('#nfcManagerTag')), save: nfcManagement.save(), unchanged: JSON.stringify(state.db) === before };
      });
      assert.deepEqual(guard, { hasEditor: false, save: false, unchanged: true });
      assert.deepEqual(errors, []);
      reports.push({ width, passed: true, draftPreserved: true, duplicateRejected: true, localSaveAtomic: true, checkDoesNotStamp: true, simulationAdminOnly: true, disabledTagRejected: true, persisted: true });
      await page.close();
    }
    fs.writeFileSync(path.join(output, 'report.json'), JSON.stringify(reports, null, 2));
    console.log(JSON.stringify(reports, null, 2));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
